export type StayType = "otel" | "pansiyon" | "apart";

export interface Room {
  name: string;
  capacity: number;
  price: number; // gecelik, ₺
  note?: string;
}

export interface Stay {
  slug: string; // sayfa adresi: /konaklama/<slug>
  name: string;
  type: StayType;
  area: string; // Merkez, Yiğitler, Değirmenardı...
  tag: string; // liste kartındaki kısa etiket
  tagline: string;
  description: string;
  priceFrom: number; // gecelik başlangıç fiyatı, ₺
  amenities: string[];
  rooms: Room[];
  nearby: { label: string; distance: string }[];
  images: string[]; // /public altındaki yollar, örn. "/img/ados-otel/1.webp"
  whatsapp: string; // 90 ile başlayan, + olmadan
  phone?: string;
  checkIn: string;
  checkOut: string;
  gradient: string; // fotoğraf yokken kullanılan Tailwind gradyanı
  featured?: boolean; // false ise ana sayfada "Diğer tesisler" bölümünde kompakt kart olarak görünür (varsayılan: true)
  kind?: string; // rozette gösterilen tür adı, örn. "Motel" (boşsa type kullanılır)
  priceNote?: string; // kompakt kartta fiyatın yanında yazan dönem/kişi bilgisi, örn. "Mayıs · oda (2 kişi)"
  // --- Arama sonuçları için isteğe bağlı başlık/açıklama; boşsa otomatik üretilir ---
  seoTitle?: string; // ~60 karakter
  seoDescription?: string; // ~155 karakter
  // --- JSON-LD (SEO) için isteğe bağlı alanlar; boş bırakırsan JSON-LD'ye eklenmez ---
  schemaType?: "Hotel" | "BedAndBreakfast" | "LodgingBusiness" | "Motel"; // boşsa türden otomatik seçilir
  streetAddress?: string; // sokak/cadde/no; doğrulanmadıysa boş bırak (uydurma adres yazma)
  addressText?: string; // ekranda görünen genel adres; boşsa bölgeden otomatik üretilir
  postalCode?: string;
  geo?: { lat: number; lng: number }; // Google Haritalar'dan alınan koordinat
  starRating?: number; // yalnızca otel için, 1-5
}

