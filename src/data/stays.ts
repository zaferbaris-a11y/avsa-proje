export interface FeatureDef {
  key: string;
  label: string;
  icon: string;
  test: RegExp;
}
export const featureDefs: FeatureDef[] = [
  { key: "deniz", label: "Denize sıfır", icon: "🌊", test: /denize (s[ıi]f[ıi]r|yak[ıi]n|\d+ ?(adım|m)\b)/i },
  { key: "havuz", label: "Havuzlu", icon: "🏊", test: /havuz/i },
  { key: "kahvalti", label: "Kahvaltı dahil", icon: "🥐", test: /kahvalt[ıi]/i },
  { key: "cocuk", label: "Çocuk dostu", icon: "👨‍👩‍👧", test: /çocuk|aile|aquapark|kaydırak/i },
  { key: "yarim", label: "Yarım pansiyon", icon: "🍽️", test: /yar[ıi]m pansiyon/i },
];
export const featuresOf = (s: Stay): FeatureDef[] => {
  const hay = [s.tag, s.tagline, ...s.amenities, ...s.rooms.map((r) => r.name)].join(" | ");
  return featureDefs.filter((f) => f.test.test(hay));
};

